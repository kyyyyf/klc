_EXACT_ONLY = {"core/skills/index_health.py"}  # allowlist must equal the literal, not just occur in it

_ALLOWED_LITERALS = (
    # (file, substring, reason)
    ("core/skills/hook_install.py", "generated by `klc install`", "load-bearing hook marker"),
    ("core/skills/hook_install.py", "BEGIN klc install", "load-bearing hook marker"),
    ("core/skills/hook_install.py", "END klc install", "load-bearing hook marker"),
    # EXACT match only: the literal passed to render_snippet as the hook command.
    ("core/skills/index_health.py", "klc update", "hook snippet command the hook pins; KLC-180"),
    ("core/phases/state.py", "klc state init", "deprecated module's own usage"),
)


def test_core_string_literals_do_not_teach_retired_commands():
    """F-006: the guard covers code messages, not only docs."""
    import ast
    pat = re.compile(r"klc (retrack|scope-fix|install|init|update|setup|state init)\b(?!:)")
    offenders = []
    files = (sorted((FW / "core" / "skills").glob("*.py")) + sorted((FW / "core" / "phases").glob("*.py"))
             + sorted((FW / "scripts").glob("*.py")))
    for f in files:
        rel = str(f.relative_to(FW))
        tree = ast.parse(f.read_text("utf-8"))
        skip = set()
        for n in ast.walk(tree):
            if isinstance(n, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) \
                    and n.body and isinstance(n.body[0], ast.Expr) \
                    and isinstance(n.body[0].value, ast.Constant):
                skip.add(id(n.body[0].value))
            if isinstance(n, ast.Call):
                skip.update(id(k.value) for k in n.keywords if k.arg == "prog")
        for n in ast.walk(tree):
            if not (isinstance(n, ast.Constant) and isinstance(n.value, str)) or id(n) in skip:
                continue
            if not pat.search(n.value) or "deprecated" in n.value.lower():
                continue
            if any(rel == a and (n.value == sub or (sub in n.value and rel not in _EXACT_ONLY))
                   for a, sub, _ in _ALLOWED_LITERALS):
                continue
            offenders.append(f"{rel}:{n.lineno}: {n.value.strip()[:80]!r}")
    assert offenders == [], "\n".join(offenders)
