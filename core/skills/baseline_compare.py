def _main_record(argv: list[str]) -> int:
    if "--" in argv:
        idx = argv.index("--")
        own_argv, backfill_args = argv[:idx], argv[idx + 1:]
    else:
        own_argv, backfill_args = argv, []
    ap = argparse.ArgumentParser(prog="baseline_compare.py record")
    ap.add_argument("--label", choices=("old", "corrected"), required=True)
    ap.add_argument("--code-dir", type=Path, required=True)
    ap.add_argument("--code-commit", required=True)
    ap.add_argument("--work-dir", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(own_argv)
    try:
        record_run(args.label, args.code_dir, args.code_commit, backfill_args,
                  args.work_dir, args.out)
    except RecordError as exc:
        sys.stderr.write(f"baseline_compare record: {exc}\n")
        return 2
    return 0


def _main_render(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="baseline_compare.py render")
    ap.add_argument("--published", type=Path, required=True)
    ap.add_argument("--published-source", required=True)
    ap.add_argument("--old", type=Path, required=True)
    ap.add_argument("--corrected", type=Path, required=True)
    ap.add_argument("--doc", type=Path, required=True)
    args = ap.parse_args(argv)
    published_text = args.published.read_text(encoding="utf-8")
    old = json.loads(args.old.read_text(encoding="utf-8"))
    corrected = json.loads(args.corrected.read_text(encoding="utf-8"))
    try:
        block = render_comparison(published_text, args.published_source, old, corrected)
        doc_text = args.doc.read_text(encoding="utf-8")
        new_doc = splice_generated(doc_text, block)
    except ValueError as exc:
        sys.stderr.write(f"baseline_compare render: {exc}\n")
        return 2
    args.doc.write_text(new_doc, encoding="utf-8")
    return 0


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if not argv:
        sys.stderr.write("baseline_compare: missing subcommand (record|render)\n")
        return 2
    sub, rest = argv[0], argv[1:]
    if sub == "record":
        return _main_record(rest)
    if sub == "render":
        return _main_render(rest)
    sys.stderr.write(f"baseline_compare: unknown subcommand {sub!r}\n")
    return 2


if __name__ == "__main__":
    sys.exit(main())
